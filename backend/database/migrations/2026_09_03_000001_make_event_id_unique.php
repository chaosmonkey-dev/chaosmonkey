use Illuminate\Database\Migrations\Migration;
use Illuminate\Support\Facades\DB;

/**
 * CR-X Pass 1 (J): Race-safe event_id uniqueness.
 *
 * The prior migration 2026_09_02_160000 added event_id as a nullable column
 * with a NON-UNIQUE index (idx_telemetry_event_id). The controller's
 * check-then-insert path (where('event_id')->first() then create()) is
 * therefore TOCTOU-vulnerable: two concurrent replays of the same event_id
 * can both pass the existence check and both insert, producing duplicate rows.
 *
 * This additive migration establishes the DB-enforced uniqueness contract:
 * - Drops the non-unique idx_telemetry_event_id
 * - Creates a COMPOSITE UNIQUE index uniq_telemetry_org_event_id on
 *   (organization_id, event_id)
 *
 * EVENT_ID CONTRACT (proven from extension source):
 * event_id is generated by generateEventId() in extension.ts as a
 * deterministic djb2 hash of: event_type + timestamp + session_id + count +
 * duration_ms + segment_type + end_reason + trigger.
 *
 * The hash input does NOT include organization_id, user_id, or
 * installation_id. Therefore event_id is NOT globally unique — two
 * organizations CAN legitimately produce the same event_id if they have
 * sessions with the same session_id and identical event content.
 *
 * The correct unique key is (organization_id, event_id) — composite.
 * This matches the multi-tenant isolation contract: within one org,
 * event_id is deterministic and must be unique (dedup). Across orgs,
 * the same event_id value is permitted.
 *
 * SQLite enforces UNIQUE only for non-NULL values, so historical rows with
 * NULL event_id remain unaffected (multiple NULLs allowed).
 *
 * Raw SQL is used because Laravel's SQLite Blueprint dropIndex/unique do not
 * reliably manipulate named indexes across SQLite versions.
 *
 * MIGRATION PRECONDITIONS:
 * - Historical NULL event_id rows: safe (SQLite allows multiple NULLs)
 * - Existing duplicate non-NULL event_ids within same org: migration will
 *   FAIL. A preflight duplicate audit is required before live promotion.
 * - Existing duplicate non-NULL event_ids across different orgs: safe
 *   (composite key includes organization_id)
 * - Rollback: restores non-unique index on event_id alone
 *
 * This migration is ADDITIVE SOURCE only. It is NOT applied to operational
 * Local in this pass (no DB TASK authorization). It is exercised only
 * against the ephemeral :memory: test DB via RefreshDatabase.
 */
